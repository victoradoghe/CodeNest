/**
 * Generates the service worker's precache list.
 *
 * The service worker itself is a hand-written static file, but it cannot know
 * two things ahead of time:
 *
 *   1. Which lesson routes exist — those come from src/content.
 *   2. What the hashed asset filenames are — Next.js only decides those during
 *      `next build`.
 *
 * So this script derives both and writes them into public/sw-precache.js, which
 * sw.js pulls in with importScripts(). Without the JS chunks in the precache a
 * page reloaded offline would render its static HTML and then never hydrate —
 * no Run button, no quiz — so the asset list is what makes offline genuinely
 * work rather than merely appear to.
 *
 * Runs automatically from the `postbuild` script.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, dirname, posix } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const CONTENT_MODULES = [
  "../src/content/modules/01-foundations.ts",
  "../src/content/modules/02-control-flow.ts",
  "../src/content/modules/03-data-structures.ts",
  "../src/content/modules/04-functions.ts",
  "../src/content/modules/05-applied.ts",
];

/** Pages that exist regardless of content. */
const STATIC_ROUTES = ["/", "/learn", "/playground", "/reference"];

// ---------------------------------------------------------------- routes

const lessonRoutes = [];
for (const path of CONTENT_MODULES) {
  // Node strips the TypeScript types natively; the content files are plain data.
  const mod = await import(new URL(path, import.meta.url).href);
  const courseModule = Object.values(mod)[0];
  for (const lesson of courseModule.lessons) {
    lessonRoutes.push(`/learn/${lesson.slug}`);
  }
}

const routes = [...STATIC_ROUTES, ...lessonRoutes];

// ---------------------------------------------------------------- assets

/** Every file under .next/static, as the URL the browser will request. */
function collectStaticAssets() {
  const staticDir = join(root, ".next", "static");
  if (!existsSync(staticDir)) return null;

  const urls = [];
  const walk = (dir, prefix) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full, posix.join(prefix, entry));
      } else {
        urls.push(posix.join("/_next/static", prefix, entry));
      }
    }
  };
  walk(staticDir, "");

  // Source maps are debugging aids, never needed to run the app offline.
  return urls.filter((url) => !url.endsWith(".map")).sort();
}

const assets = collectStaticAssets();

if (assets === null) {
  console.error(
    "[sw] .next/static not found — run `next build` before generating the precache list.",
  );
  process.exit(1);
}

// ---------------------------------------------------------------- versions

/**
 * Pyodide lives at fixed, unhashed paths (/pyodide/pyodide.asm.wasm and
 * friends), so its cache is keyed on the package version instead. That way an
 * ordinary app deploy does not force learners to re-download 12 MB, but a
 * Pyodide upgrade does — serving a new pyodide.mjs against a stale wasm binary
 * would break the interpreter in a deeply confusing way.
 */
const pyodideVersion = JSON.parse(
  readFileSync(join(root, "node_modules", "pyodide", "package.json"), "utf8"),
).version;

/** Changing any precached URL rotates the cache name, evicting the old build. */
const version = createHash("sha256")
  .update(JSON.stringify({ routes, assets }))
  .digest("hex")
  .slice(0, 12);

// ---------------------------------------------------------------- write

const banner = `/* GENERATED by scripts/generate-sw-precache.mjs — do not edit. */`;

writeFileSync(
  join(root, "public", "sw-precache.js"),
  `${banner}
self.__SW_VERSION = ${JSON.stringify(version)};
self.__PYODIDE_VERSION = ${JSON.stringify(pyodideVersion)};
self.__SW_ROUTES = ${JSON.stringify(routes, null, 2)};
self.__SW_ASSETS = ${JSON.stringify(assets, null, 2)};
`,
  "utf8",
);

console.log(
  `[sw] Precache list written: ${routes.length} routes, ${assets.length} assets ` +
    `(build ${version}, Pyodide ${pyodideVersion}).`,
);
